use Glpi\ContentTemplates\Parameters\AssetParameters;
use Glpi\ContentTemplates\Parameters\ParametersTypes\AttributeParameter;
use Glpi\Plugin\Hooks;

/**
 * Fields values in the texts generated by GLPI:
 * - notification tags of the notified item: ##fields.<container>.<field>## for the value,
 *   ##lang.fields.<container>.<field>## for the label;
 * - variables of the followup, task and solution templates: {{ ticket.fields.<container>.<field> }}
 *   (or change., problem.), {{ asset.fields.<container>.<field> }} for the assets linked to a ticket.
 */
final class PluginFieldsNotificationTag
{
    /**
     * Itemtypes of the followup, task and solution templates, by node name of their variables
     */
    private const TEMPLATE_ITEMTYPES = [
        'ticket'  => Ticket::class,
        'change'  => Change::class,
        'problem' => Problem::class,
    ];

    /**
     * Notified itemtype by notification target class
     *
     * @var array<class-string<NotificationTarget>, class-string<CommonDBTM>>
     */
    private static array $itemtypes = [];

    /**
     * Fields by itemtype and language, a notification being sent to several recipients
     *
     * @var array<string, array<int, array<string, mixed>>>
     */
    private static array $fields_cache = [];

    /**
     * @param string[] $itemtypes Itemtypes having containers
     */
    public static function registerHooks(array $itemtypes): void
    {
        /** @var array $PLUGIN_HOOKS */
        /** @var array $CFG_GLPI */
        global $PLUGIN_HOOKS, $CFG_GLPI;

        self::$itemtypes    = [];
        self::$fields_cache = [];

        // GLPI calls plugin_fields_get_content_template_*() for the plugins registering these hooks
        if (array_intersect($itemtypes, [...array_values(self::TEMPLATE_ITEMTYPES), ...$CFG_GLPI['asset_types']]) !== []) {
            $PLUGIN_HOOKS[Hooks::GET_CONTENT_TEMPLATE_PARAMETER]['fields'] = true;
            $PLUGIN_HOOKS[Hooks::GET_CONTENT_TEMPLATE_VALUE]['fields']     = true;
        }

        foreach ($itemtypes as $itemtype) {
            $target_class = NotificationTarget::getInstanceClass($itemtype);
            // not every itemtype has notifications (Computer, etc.)
            if (!class_exists($target_class)) {
                continue;
            }

            self::$itemtypes[$target_class] = $itemtype;

            // GLPI has no hook to declare tags: ITEM_ADD_TARGETS is the one run by the target
            // constructor, so the tags are listed in the "Tags" tab of the notification templates.
            $PLUGIN_HOOKS[Hooks::ITEM_ADD_TARGETS]['fields'][$target_class]        = self::addTags(...);
            $PLUGIN_HOOKS[Hooks::ADD_RECIPIENT_TO_TARGET]['fields'][$target_class] = self::addRecipient(...);
            $PLUGIN_HOOKS[Hooks::ITEM_GET_DATA]['fields'][$target_class]           = self::addData(...);
        }
    }

    /**
     * Pass the recipient to the template data, so that the values of a container
     * are only sent to the users who can read it (see addData()).
     *
     * The data being computed once by set of recipient options, this computes it by recipient.
     */
    public static function addRecipient(NotificationTarget $target): void
    {
        $users_id = self::getRecipientUserId($target);
        if ($users_id === 0 || self::getFields(self::$itemtypes[$target::class] ?? '') === []) {
            return;
        }

        foreach ($target->target as $key => $infos) {
            /** @var array<string, mixed> $infos `users_id` is set for GLPI users, but missing from the GLPI PHPDoc */
            if ((int) ($infos['users_id'] ?? 0) === $users_id) {
                $target->target[$key]['additionnaloption']['users_id'] = $users_id;
            }
        }
    }

    public static function addTags(NotificationTarget $target): void
    {
        foreach (self::getFields(self::$itemtypes[$target::class] ?? '') as $field) {
            $target->addTagToList([
                'tag'   => self::getTagName($field),
                'label' => $field['container_label'] . ' - ' . $field['label'],
                'value' => true,
            ]);
        }
    }

    public static function addData(NotificationTarget $target): void
    {
        $item = $target->obj;
        // no single item for some events (ex: alerts of the cron)
        $has_item = $item instanceof CommonDBTM && !$item->isNewItem();

        $readable_containers = $has_item
            ? self::getReadableContainers(
                self::getRecipientUserId($target),
                $item->isEntityAssign() ? $item->getEntityID() : 0,
            )
            : [];

        $values = [];
        foreach (self::getFields(self::$itemtypes[$target::class] ?? '') as $field) {
            $container_id = (int) $field['plugin_fields_containers_id'];
            if (!array_key_exists($container_id, $values)) {
                $values[$container_id] = in_array($container_id, $readable_containers, true)
                    ? self::getValues($item, $field)
                    : null;
            }

            $tag = self::getTagName($field);
            // a tag without value is set anyway, otherwise it would be sent as is
            $target->data['##' . $tag . '##']      = $values[$container_id] === null ? '' : self::formatValue($field, $values[$container_id]);
            $target->data['##lang.' . $tag . '##'] = $field['label'];
        }
    }

    /**
     * Variables of the followup, task and solution templates (twig), listed in the documentation
     * of the variables, see plugin_fields_get_content_template_parameter():
     * {{ ticket.fields.<container>.<field> }} (or change., problem.) for the item, and
     * {{ asset.fields.<container>.<field> }} in {% for asset in ticket.assets %} for the linked assets
     *
     * @return AttributeParameter[]
     */
    public static function getTemplateParameters(?string $node_name): array
    {
        /** @var array $CFG_GLPI */
        global $CFG_GLPI;

        $itemtypes = $node_name === AssetParameters::getDefaultNodeName()
            ? $CFG_GLPI['asset_types']
            : [self::TEMPLATE_ITEMTYPES[$node_name] ?? ''];

        $parameters = [];
        foreach ($itemtypes as $itemtype) {
            foreach (self::getFields($itemtype) as $field) {
                $label = $field['container_label'] . ' - ' . $field['label'];
                $parameters[] = new AttributeParameter(
                    sprintf('fields.%s.%s', $field['container_name'], $field['name']),
                    // a container may be used by several asset types
                    count($itemtypes) > 1 ? $itemtype::getTypeName(1) . ' - ' . $label : $label,
                    match ($field['type']) {
                        // a rich text value is HTML, cleaned by GLPI after the rendering
                        'richtext' => 'raw',
                        'textarea' => 'nl2br',
                        default    => '',
                    },
                );
            }
        }

        return $parameters;
    }

    /**
     * Values of the template variables for the item on which the template is used.
     * See plugin_fields_get_content_template_value()
     *
     * Values are not filtered on the rights of the current profile: the template is written by an
     * administrator, who chooses the values it shows, and may be applied by a form submitted
     * by a requester (to help the technicians handle the ticket).
     *
     * @return array{fields?: array<string, array<string, string>>, assets?: array<int, array<string, mixed>>}
     */
    public static function getTemplateValues(string $node_name, int $items_id): array
    {
        /** @var array $CFG_GLPI */
        global $CFG_GLPI;

        $itemtype = self::TEMPLATE_ITEMTYPES[$node_name] ?? null;
        if ($itemtype === null || ($item = $itemtype::getById($items_id)) === false) {
            return [];
        }

        $values = [];
        if (self::getFields($itemtype) !== []) {
            $values['fields'] = self::getVariables($item);
        }

        // The values of a plugin replace the ones of GLPI: the linked assets are built as GLPI does
        // (see TicketParameters::defineValues()), with their fields in addition.
        $assets_with_fields = array_filter(
            $CFG_GLPI['asset_types'],
            fn(string $asset_itemtype): bool => self::getFields($asset_itemtype) !== [],
        );
        if ($item instanceof Ticket && $assets_with_fields !== []) {
            $assets = [];
            foreach (Item_Ticket::getItemsAssociatedTo(Ticket::class, $item->getID()) as $item_ticket) {
                $asset_itemtype = $item_ticket->fields['itemtype'];
                if (
                    !in_array($asset_itemtype, $CFG_GLPI['asset_types'], true)
                    || !class_exists($asset_itemtype)
                    || ($asset = $asset_itemtype::getById($item_ticket->fields['items_id'])) === false
                ) {
                    continue;
                }

                $asset_values = (new AssetParameters())->getValues($asset);
                if (in_array($asset_itemtype, $assets_with_fields, true)) {
                    $asset_values['fields'] = self::getVariables($asset);
                }

                $assets[] = $asset_values;
            }

            $values['assets'] = $assets;
        }

        return $values;
    }

    /**
     * @return array<string, array<string, string>> Displayed values by container and field name
     */
    private static function getVariables(CommonDBTM $item): array
    {
        $values = [];
        $variables = [];
        foreach (self::getFields($item::class) as $field) {
            $container_id = (int) $field['plugin_fields_containers_id'];
            if (!array_key_exists($container_id, $values)) {
                $values[$container_id] = self::getValues($item, $field);
            }

            $variables[$field['container_name']][$field['name']] = $values[$container_id] === null
                ? ''
                : self::formatValue($field, $values[$container_id]);
        }

        return $variables;
    }

    private static function getRecipientUserId(NotificationTarget $target): int
    {
        return ($target->recipient_data['itemtype'] ?? null) === User::class
            ? (int) ($target->recipient_data['items_id'] ?? 0)
            : 0;
    }

    /**
     * Containers readable by a profile of the user in the entity, none for a recipient
     * without GLPI account (email address of a requester, etc.)
     *
     * @return int[]
     */
    private static function getReadableContainers(int $users_id, int $entities_id): array
    {
        /** @var DBmysql $DB */
        global $DB;

        if ($users_id <= 0) {
            return [];
        }

        $profiles = Profile_User::getUserProfiles(
            $users_id,
            getEntitiesRestrictCriteria(Profile_User::getTable(), 'entities_id', $entities_id, true),
        );

        if ($profiles === []) {
            return [];
        }

        $containers = [];
        $iterator = $DB->request([
            'SELECT'   => 'plugin_fields_containers_id',
            'DISTINCT' => true,
            'FROM'     => PluginFieldsProfile::getTable(),
            'WHERE'    => [
                'profiles_id' => array_values($profiles),
                'right'       => ['>=', READ],
            ],
        ]);
        foreach ($iterator as $data) {
            $containers[] = (int) $data['plugin_fields_containers_id'];
        }

        return $containers;
    }

    /**
     * Active fields of the active containers of the itemtype, with translated labels
     *
     * @return array<int, array<string, mixed>>
     */
    private static function getFields(string $itemtype): array
    {
        /** @var DBmysql $DB */
        global $DB;

        if ($itemtype === '') {
            return [];
        }

        $cache_key = $itemtype . '|' . ($_SESSION['glpilanguage'] ?? '');
        if (isset(self::$fields_cache[$cache_key])) {
            return self::$fields_cache[$cache_key];
        }

        $containers = [];
        foreach ((new PluginFieldsContainer())->find(['is_active' => 1]) as $container) {
            $container_itemtypes = PluginFieldsToolbox::decodeJSONItemtypes($container['itemtypes']);
            if (is_array($container_itemtypes) && in_array($itemtype, $container_itemtypes, true)) {
                $container['label'] = PluginFieldsLabelTranslation::getLabelFor($container + ['itemtype' => PluginFieldsContainer::class]);
                $containers[$container['id']] = $container;
            }
        }

        if ($containers === []) {
            return self::$fields_cache[$cache_key] = [];
        }

        $fields = [];
        $iterator = $DB->request([
            'FROM'  => PluginFieldsField::getTable(),
            'WHERE' => [
                'plugin_fields_containers_id' => array_keys($containers),
                'is_active'                   => 1,
                'NOT'                         => ['type' => 'header'],
            ],
            'ORDER' => ['plugin_fields_containers_id', 'ranking'],
        ]);
        foreach ($iterator as $field) {
            $container = $containers[$field['plugin_fields_containers_id']];

            $field['label']              = PluginFieldsLabelTranslation::getLabelFor($field + ['itemtype' => PluginFieldsField::class]);
            $field['container_name']     = $container['name'];
            $field['container_label']    = $container['label'];
            $field['container_entity']   = $container['entities_id'];
            $field['container_recursive'] = $container['is_recursive'];
            $field['itemtype']           = $itemtype;
            $fields[] = $field;
        }

        return self::$fields_cache[$cache_key] = $fields;
    }

    private static function getTagName(array $field): string
    {
        return sprintf('fields.%s.%s', $field['container_name'], $field['name']);
    }

    /**
     * Values stored by the container of the field for the item,
     * empty if none is stored, null if the container does not apply to the item entity
     *
     * @return array<string, mixed>|null
     */
    private static function getValues(CommonDBTM $item, array $field): ?array
    {
        if ($item->isEntityAssign()) {
            $entity = $item->getEntityID();
            $container_entities = $field['container_recursive']
                ? getSonsOf(Entity::getTable(), $field['container_entity'])
                : [$field['container_entity']];
            if (!in_array($entity, $container_entities)) {
                return null;
            }
        }

        $classname = PluginFieldsContainer::getClassname($field['itemtype'], $field['container_name']);
        if (!class_exists($classname)) {
            return [];
        }

        $values = (new $classname())->find([
            'plugin_fields_containers_id' => $field['plugin_fields_containers_id'],
            'items_id'                    => $item->getID(),
        ], [], 1);

        return array_shift($values) ?? [];
    }

    /**
     * Value of the field as displayed to the user
     */
    private static function formatValue(array $field, array $values): string
    {
        $name = $field['name'];
        $type = $field['type'];

        if ($type === 'glpi_item') {
            $itemtype = $values['itemtype_' . $name] ?? null;
            $items_id = (int) ($values['items_id_' . $name] ?? 0);
            if (!is_string($itemtype) || !is_a($itemtype, CommonDBTM::class, true) || $items_id <= 0) {
                return '';
            }

            $linked_item = $itemtype::getById($items_id);
            return $linked_item === false ? '' : $linked_item->getName();
        }

        $value = $values[$type === 'dropdown' ? 'plugin_fields_' . $name . 'dropdowns_id' : $name] ?? null;
        // same default value as the search, the current date is not one for an existing item
        if (($value === null || $value === '') && $field['default_value'] !== 'now') {
            $value = $field['default_value'];
        }

        if ($value === null || $value === '') {
            return '';
        }

        $dropdown_matches = [];
        $dropdown_itemtype = match (true) {
            $type === 'dropdown' => PluginFieldsDropdown::getClassname($name),
            preg_match('/^dropdown-(?<class>.+)$/i', $type, $dropdown_matches) === 1 => $dropdown_matches['class'],
            default => null,
        };

        if ($dropdown_itemtype !== null) {
            if (!is_a($dropdown_itemtype, CommonDBTM::class, true)) {
                return ''; // itemtype of a disabled plugin
            }

            $ids = $field['multiple'] ? json_decode((string) $value, true) : [$value];
            $names = [];
            foreach (is_array($ids) ? $ids : [] as $id) {
                if ((int) $id > 0) {
                    $names[] = Dropdown::getDropdownName($dropdown_itemtype::getTable(), (int) $id);
                }
            }

            return implode(', ', array_filter($names, fn($name) => $name !== ''));
        }

        return match ($type) {
            'yesno'    => Dropdown::getYesNo((int) $value),
            'date'     => (string) Html::convDate((string) $value),
            'datetime' => (string) Html::convDateTime((string) $value),
            default    => (string) $value,
        };
    }
}
