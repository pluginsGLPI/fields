declare(strict_types=1);

namespace GlpiPlugin\Field\Tests\Units;

use Computer;
use DBmysql;
use Glpi\Tests\DbTestCase;
use Glpi\Tests\GLPITestCase;
use GlpiPlugin\Field\Tests\FieldTestTrait;
use PluginFieldsContainer;
use PluginFieldsField;

require_once __DIR__ . '/../FieldTestCase.php';
require_once __DIR__ . '/../../hook.php';

final class InstallOutdatedGeneratedFilesTest extends DbTestCase
{
    use FieldTestTrait;

    public function setUp(): void
    {
        GLPITestCase::setUp();
        $this->login();
    }

    public function tearDown(): void
    {
        $this->tearDownFieldTest();
        GLPITestCase::tearDown();
    }

    public function testInstallDoesNotLoadOutdatedGeneratedDropdownClass(): void
    {
        /** @var DBmysql $DB */
        global $DB;

        $container = $this->createFieldContainer([
            'label'       => 'Outdated files container',
            'type'        => 'tab',
            'itemtypes'   => [Computer::class],
            'is_active'   => 1,
            'entities_id' => 0,
        ]);

        $field = $this->createField([
            'label'                                     => 'Outdated dropdown',
            'type'                                      => 'dropdown',
            PluginFieldsContainer::getForeignKeyField() => $container->getID(),
            'ranking'                                   => 1,
            'is_active'                                 => 1,
            'is_readonly'                               => 0,
        ]);
        $this->assertSame('outdateddropdownfield', $field->fields['name']);

        // Simulate a dropdown generated by a previous plugin version, with a system name that does not match
        // its label anymore (it will be renamed by the migration) and a class that has not been loaded yet.
        $old_name             = 'notloadedyetfield';
        $container_classname  = PluginFieldsContainer::getClassname(Computer::class, $container->fields['name']);
        $container_table      = getTableForItemType($container_classname);
        $container_class_file = PLUGINFIELDS_CLASS_PATH . '/' . strtolower(substr($container_classname, strlen('PluginFields'))) . '.class.php';
        $DB->update(PluginFieldsField::getTable(), ['name' => $old_name], ['id' => $field->getID()]);
        $DB->doQuery('RENAME TABLE `glpi_plugin_fields_outdateddropdownfielddropdowns` TO `glpi_plugin_fields_notloadedyetfielddropdowns`');
        $DB->doQuery(
            "ALTER TABLE `{$container_table}` CHANGE `plugin_fields_outdateddropdownfielddropdowns_id` `plugin_fields_notloadedyetfielddropdowns_id` INT UNSIGNED DEFAULT NULL",
        );

        // Outdated class file, that would trigger a fatal error if loaded (e.g. incompatible property declaration).
        $outdated_file = PLUGINFIELDS_CLASS_PATH . '/' . $old_name . 'dropdown.class.php';
        file_put_contents($outdated_file, '<?php throw new \RuntimeException("Outdated generated class has been loaded.");');
        $this->assertFileExists($container_class_file);

        ob_start();
        $result = plugin_fields_install();
        ob_end_clean();
        $DB->clearSchemaCache();

        $this->assertTrue($result);

        // Outdated file has been removed, dropdown has been renamed and its files regenerated
        $this->assertFileDoesNotExist($outdated_file);
        $this->assertTrue($field->getFromDB($field->getID()));
        $this->assertSame('outdateddropdownfield', $field->fields['name']);
        $this->assertTrue($DB->tableExists('glpi_plugin_fields_outdateddropdownfielddropdowns'));
        $this->assertFileExists(PLUGINFIELDS_CLASS_PATH . '/outdateddropdownfielddropdown.class.php');
        $this->assertFileExists($container_class_file);
    }
}
